#!/usr/bin/env python3
"""Register a fresh Juice Shop test user and store its credentials in sut/fixtures/.env.eval.

The password is generated here, written only to .env.eval (gitignored), and never printed.
Juice Shop recreates its SQLite DB on every start, so run this again after each restart.

    python sut/fixtures/create_test_user.py [--base-url http://127.0.0.1:3000] [--env-file PATH]

Written keys:
    JUICE_SHOP_BASE_URL, JUICE_SHOP_USER_EMAIL, JUICE_SHOP_USER_PASSWORD,
    JUICE_SHOP_USER_ID, JUICE_SHOP_BASKET_ID, JUICE_SHOP_USER_CREATED_AT
"""
from __future__ import annotations

import argparse
import json
import os
import secrets
import string
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_ENV_FILE = HERE / ".env.eval"
DEFAULT_BASE_URL = "http://127.0.0.1:3000"  # direct to Juice Shop, so proxy faults cannot break setup


class ApiError(RuntimeError):
    pass


def call(base: str, method: str, path: str, body: dict | None = None, token: str | None = None) -> dict:
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(base.rstrip("/") + path, data=data, method=method)
    req.add_header("Content-Type", "application/json")
    req.add_header("Accept", "application/json")
    if token:
        req.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(req, timeout=15) as resp:
            return json.loads(resp.read() or b"{}")
    except urllib.error.HTTPError as e:
        # Do not echo the request body (contains the password); status + path is enough.
        raise ApiError(f"{method} {path} -> HTTP {e.code}") from None


def make_password() -> str:
    alphabet = string.ascii_letters + string.digits
    core = "".join(secrets.choice(alphabet) for _ in range(20))
    return f"Pf{core}!9"  # guarantees upper, lower, digit, symbol


def write_env(path: Path, values: dict[str, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Generated by sut/fixtures/create_test_user.py. Gitignored. Do not commit or print."]
    lines += [f"{k}={v}" for k, v in values.items()]
    tmp = path.with_name(path.name + ".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    os.replace(tmp, path)


def create_user(base_url: str) -> dict[str, str]:
    email = f"perf-eval-{int(time.time())}-{secrets.token_hex(3)}@juice-sh.op"
    password = make_password()
    question = (call(base_url, "GET", "/api/SecurityQuestions").get("data") or [{"id": 1}])[0]
    answer = secrets.token_hex(8)
    created = call(base_url, "POST", "/api/Users", {
        "email": email,
        "password": password,
        "passwordRepeat": password,
        "securityQuestion": question,
        "securityAnswer": answer,
    })
    user_id = created.get("data", {}).get("id")
    if not user_id:
        raise ApiError("registration response has no user id")
    call(base_url, "POST", "/api/SecurityAnswers", {"UserId": user_id, "answer": answer, "SecurityQuestionId": question["id"]})
    auth = call(base_url, "POST", "/rest/user/login", {"email": email, "password": password}).get("authentication") or {}
    if not auth.get("token"):
        raise ApiError("login with new user returned no token")
    return {
        "JUICE_SHOP_BASE_URL": base_url.rstrip("/"),
        "JUICE_SHOP_USER_EMAIL": email,
        "JUICE_SHOP_USER_PASSWORD": password,
        "JUICE_SHOP_USER_ID": str(user_id),
        "JUICE_SHOP_BASKET_ID": str(auth.get("bid", "")),
        "JUICE_SHOP_USER_CREATED_AT": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base-url", default=os.environ.get("JUICE_SHOP_BASE_URL", DEFAULT_BASE_URL))
    ap.add_argument("--env-file", type=Path, default=DEFAULT_ENV_FILE)
    args = ap.parse_args(argv)
    try:
        values = create_user(args.base_url)
    except (ApiError, urllib.error.URLError, OSError) as e:
        print(f"create_test_user: failed: {e}", file=sys.stderr)
        return 1
    write_env(args.env_file, values)
    print(f"created test user {values['JUICE_SHOP_USER_EMAIL']} (id {values['JUICE_SHOP_USER_ID']}); "
          f"credentials written to {args.env_file}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
